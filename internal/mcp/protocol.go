// Package mcp implements ProxyForge's Model Context Protocol server
// (Phase 4): stdio + streamable HTTP transports, the tool catalog from the
// project brief, history/issues resources, workflow prompts, and
// untrusted-content provenance on everything that carries captured traffic.
package mcp

import "encoding/json"

// JSONRPC 2.0 envelope types (MCP's wire format).

type Request struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      json.RawMessage `json:"id,omitempty"`
	Method  string          `json:"method"`
	Params  json.RawMessage `json:"params,omitempty"`
}

type Error struct {
	Code    int    `json:"code"`
	Message string `json:"message"`
}

type Response struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      json.RawMessage `json:"id"`
	Result  json.RawMessage `json:"result,omitempty"`
	Error   *Error          `json:"error,omitempty"`
}

// Standard JSON-RPC error codes.
const (
	CodeParseError     = -32700
	CodeInvalidRequest = -32600
	CodeMethodNotFound = -32601
	CodeInvalidParams  = -32602
	CodeInternal       = -32603
)

func NewResult(id json.RawMessage, v any) Response {
	raw, err := json.Marshal(v)
	if err != nil {
		return NewError(id, CodeInternal, err.Error())
	}
	return Response{JSONRPC: "2.0", ID: id, Result: raw}
}

func NewError(id json.RawMessage, code int, msg string) Response {
	return Response{JSONRPC: "2.0", ID: id, Error: &Error{Code: code, Message: msg}}
}

// --- MCP result shapes ---

// Content is a text block (all ProxyForge tool results are text).
type Content struct {
	Type string `json:"type"`
	Text string `json:"text"`
}

// ToolResult is the tools/call result envelope.
type ToolResult struct {
	Content []Content `json:"content"`
	IsError bool      `json:"isError,omitempty"`
}

// Tool def for tools/list.
type Tool struct {
	Name        string         `json:"name"`
	Description string         `json:"description"`
	InputSchema map[string]any `json:"inputSchema"`
}

// Resource def.
type Resource struct {
	URI      string `json:"uri"`
	Name     string `json:"name"`
	MimeType string `json:"mimeType"`
}

// ResourceContents for resources/read.
type ResourceContents struct {
	URI      string `json:"uri"`
	MimeType string `json:"mimeType"`
	Text     string `json:"text"`
}

// ReadResourceResult envelopes contents.
type ReadResourceResult struct {
	Contents []ResourceContents `json:"contents"`
}

// PromptMessage is one message in a prompt.
type PromptMessage struct {
	Role    string  `json:"role"`
	Content Content `json:"content"`
}

// Prompt def.
type Prompt struct {
	Name        string `json:"name"`
	Description string `json:"description"`
}

// GetPromptResult envelopes prompt messages.
type GetPromptResult struct {
	Description string          `json:"description,omitempty"`
	Messages    []PromptMessage `json:"messages"`
}

// InitializeResult is the handshake reply.
type InitializeResult struct {
	ProtocolVersion string `json:"protocolVersion"`
	Capabilities    struct {
		Tools     map[string]any `json:"tools,omitempty"`
		Resources map[string]any `json:"resources,omitempty"`
		Prompts   map[string]any `json:"prompts,omitempty"`
	} `json:"capabilities"`
	ServerInfo struct {
		Name    string `json:"name"`
		Version string `json:"version"`
	} `json:"serverInfo"`
}

// Provenance mirrors the REA untrusted-content convention: every tool
// result that embeds captured traffic carries this marker so the agent (and
// its instructions) can treat embedded text as data, never directives.
type Provenance struct {
	UntrustedContent bool   `json:"untrusted_content"`
	Source           string `json:"source"`
}

// Envelope is the standard tool-result payload: data plus provenance meta.
type Envelope struct {
	Data any        `json:"data"`
	Meta Provenance `json:"_meta"`
}

// WrapCaptured builds an envelope for results carrying captured content.
func WrapCaptured(data any) Envelope {
	return Envelope{Data: data, Meta: Provenance{UntrustedContent: true, Source: "captured_traffic"}}
}

// WrapOwn builds an envelope for results generated by ProxyForge itself.
func WrapOwn(data any) Envelope {
	return Envelope{Data: data, Meta: Provenance{UntrustedContent: false, Source: "proxyforge"}}
}
