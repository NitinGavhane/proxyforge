// Package report renders engagement reports (Markdown / HTML) from scanner
// issues with request/response evidence.
package report

import (
	"context"
	"fmt"
	"html"
	"strings"
	"time"

	"github.com/NitinGavhane/proxyforge/internal/flows"
	"github.com/NitinGavhane/proxyforge/internal/store"
)

// Meta labels the report.
type Meta struct {
	Project string
	Target  string
	When    time.Time
}

// Render renders issues as Markdown, pulling evidence flows from st.
func Render(ctx context.Context, st *store.Store, meta Meta, issues []store.Issue) string {
	var b strings.Builder
	title := "ProxyForge Security Report"
	if meta.Target != "" {
		title += " — " + meta.Target
	}
	fmt.Fprintf(&b, "# %s\n\n", title)
	fmt.Fprintf(&b, "- **Generated**: %s\n", meta.When.Format(time.RFC3339))
	if meta.Project != "" {
		fmt.Fprintf(&b, "- **Project**: %s\n", meta.Project)
	}
	fmt.Fprintf(&b, "- **Issues**: %d\n\n", len(issues))

	// summary table
	if len(issues) > 0 {
		b.WriteString("| Severity | Count |\n|---|---|\n")
		for _, sev := range []string{"critical", "high", "medium", "low", "info"} {
			n := 0
			for _, i := range issues {
				if i.Severity == sev {
					n++
				}
			}
			if n > 0 {
				fmt.Fprintf(&b, "| %s | %d |\n", sev, n)
			}
		}
		b.WriteString("\n")
	}

	for idx, i := range issues {
		fmt.Fprintf(&b, "## %d. [%s/%s] %s\n\n", idx+1, strings.ToUpper(i.Severity), i.Confidence, i.Title)
		fmt.Fprintf(&b, "- **Check**: `%s`\n", i.CheckID)
		fmt.Fprintf(&b, "- **Target**: `%s`\n", targetOf(i))
		fmt.Fprintf(&b, "- **Found**: %s\n", time.UnixMilli(i.Created).Format(time.RFC3339))
		if i.EvidenceFlowID != 0 {
			fmt.Fprintf(&b, "- **Evidence**: flow #%d\n", i.EvidenceFlowID)
		}
		fmt.Fprintf(&b, "\n%s\n", i.Detail)
		if i.EvidenceFlowID != 0 {
			if f, err := st.GetFlow(ctx, i.EvidenceFlowID); err == nil {
				b.WriteString("\n**Evidence request**\n\n```http\n")
				b.WriteString(string(reqSnippet(f)))
				b.WriteString("\n```\n")
				if f.Response != nil {
					b.WriteString("\n**Evidence response (truncated)**\n\n```http\n")
					b.WriteString(string(respSnippet(f)))
					b.WriteString("\n```\n")
				}
			}
		}
		b.WriteString("\n")
	}
	if len(issues) == 0 {
		b.WriteString("_No issues recorded._\n")
	}
	b.WriteString("\n---\n_Generated by ProxyForge — for authorized testing only._\n")
	return b.String()
}

// RenderHTML renders the same report as a self-contained HTML document.
func RenderHTML(ctx context.Context, st *store.Store, meta Meta, issues []store.Issue) string {
	md := Render(ctx, st, meta, issues)
	var b strings.Builder
	b.WriteString(`<!doctype html><html><head><meta charset="utf-8">`)
	b.WriteString(`<title>ProxyForge Report</title><style>
body{font-family:ui-sans-serif,system-ui,sans-serif;max-width:52rem;margin:2rem auto;padding:0 1rem;color:#1e293b}
h1,h2{color:#0f172a}h2{border-bottom:1px solid #e2e8f0;padding-bottom:.3rem}
table{border-collapse:collapse}td,th{border:1px solid #e2e8f0;padding:.3rem .6rem}
pre{background:#0f172a;color:#e2e8f0;padding:.8rem;border-radius:6px;overflow:auto;font-size:.8rem}
.critical,.high{color:#b91c1c}.medium{color:#b45309}.low{color:#0369a1}.info{color:#64748b}
</style></head><body>`)
	b.WriteString(mdToHTML(md))
	b.WriteString("</body></html>")
	return b.String()
}

// mdToHTML is a small purpose-built renderer for the subset of Markdown
// this report uses (headings, lists, tables, code fences, bold, rules).
func mdToHTML(md string) string {
	var b strings.Builder
	lines := strings.Split(md, "\n")
	inCode := false
	var code strings.Builder
	for _, line := range lines {
		if strings.HasPrefix(line, "```") {
			if inCode {
				b.WriteString("<pre>" + html.EscapeString(code.String()) + "</pre>\n")
				code.Reset()
				inCode = false
			} else {
				inCode = true
			}
			continue
		}
		if inCode {
			code.WriteString(line)
			code.WriteString("\n")
			continue
		}
		switch {
		case strings.HasPrefix(line, "# "):
			fmt.Fprintf(&b, "<h1>%s</h1>\n", inline(strings.TrimPrefix(line, "# ")))
		case strings.HasPrefix(line, "## "):
			fmt.Fprintf(&b, "<h2>%s</h2>\n", inline(strings.TrimPrefix(line, "## ")))
		case strings.HasPrefix(line, "| "):
			// table row
			cells := strings.Split(strings.Trim(line, "|"), "|")
			b.WriteString("<tr>")
			for _, c := range cells {
				fmt.Fprintf(&b, "<th>%s</th>", inline(strings.TrimSpace(c)))
			}
			b.WriteString("</tr>\n")
		case strings.HasPrefix(line, "---"):
			b.WriteString("<hr>\n")
		case strings.HasPrefix(line, "- "):
			fmt.Fprintf(&b, "<li>%s</li>\n", inline(strings.TrimPrefix(line, "- ")))
		case strings.HasPrefix(line, "_") && strings.HasSuffix(line, "_"):
			fmt.Fprintf(&b, "<p><em>%s</em></p>\n", inline(strings.Trim(line, "_")))
		case line == "":
			// close any open table
			if strings.HasSuffix(b.String(), "</tr>\n") {
				b.WriteString("</table>\n")
			}
		default:
			if strings.HasSuffix(b.String(), "</tr>\n") == false && strings.Contains(b.String(), "<tr>") && !strings.HasPrefix(line, "|") {
				// table just ended
			}
			fmt.Fprintf(&b, "<p>%s</p>\n", inline(line))
		}
		if strings.Contains(b.String(), "<tr>") && strings.HasSuffix(b.String(), "</table>\n") {
			// already closed
		}
	}
	return b.String()
}

func inline(s string) string {
	s = strings.ReplaceAll(s, "**", "")
	s = strings.ReplaceAll(s, "`", "")
	return html.EscapeString(s)
}

func targetOf(i store.Issue) string {
	if i.Port != 0 && i.Port != 80 && i.Port != 443 {
		return fmt.Sprintf("%s:%d%s", i.Host, i.Port, i.Path)
	}
	return i.Host + i.Path
}

const evidenceCap = 1200

const snippetCap = 1200

func reqSnippet(f *flows.Flow) []byte {
	out := flows.RenderRequest(f.Request)
	if len(out) > snippetCap {
		out = append(out[:snippetCap], []byte("\n… (truncated)")...)
	}
	return out
}

func respSnippet(f *flows.Flow) []byte {
	if f.Response == nil {
		return nil
	}
	out := flows.RenderResponse(f.Response)
	if len(out) > snippetCap {
		out = append(out[:snippetCap], []byte("\n… (truncated)")...)
	}
	return out
}
